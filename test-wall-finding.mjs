#!/usr/bin/env node

/**
 * test-wall-finding.mjs — an unreadable form is recorded, not silently skipped.
 *
 * WHY THIS EXISTS. batch/ready-check.py failed the nightly for at least ten
 * nights (2026-08-23 → 2026-09-02), 46 cards `no answers.md`, 45 of them
 * cityjobs.nyc.gov. NYC Jobs requires an account before the application form
 * exists, so generate-answers.mjs printed `SKIP … form not enumerable` and wrote
 * nothing — a structural fact about the employer's site, reported every night
 * as a pack defect. The OLAS login wall already had the right answer: a dated
 * finding in answers.md that ready-check accepts as evidence.
 *
 * This pins three things:
 *   1. cityjobs.nyc.gov is a KNOWN wall, recorded directly — and OLAS is not on
 *      that list, because its wall is observed on the page, the stronger claim.
 *   2. The finding carries exactly what the downstream readers key on: the
 *      `Form inspected: <date>` marker ready-check.py accepts (regex mirrored
 *      here), the phrase parseAnswersMd() reads as loginWall, and the generator
 *      footer canRewrite() needs.
 *   3. ⚠ The finding contains NO answer. Not a table, not a draft, not a
 *      blank-by-design row. The deny list runs before drafting and this path
 *      never reaches either; a finding that drafted would be a fabricated form.
 */
import { KNOWN_ACCOUNT_WALLS, knownAccountWall, renderWallFinding } from './generate-answers.mjs';
import { parseAnswersMd } from './lib/cover-letter-requirement.mjs';

const T = [];
const eq = (label, got, want) => T.push([label, got, want]);

// Mirror of batch/ready-check.py's INSPECTED marker (the current convention).
// If that regex changes, change this one — the point is to pin agreement.
const INSPECTED = /form\s+inspected\D{0,20}\d{4}-\d{2}-\d{2}/i;

// ── 1. the known-wall list ────────────────────────────────────────────────
const nyc = knownAccountWall('https://cityjobs.nyc.gov/job/790198');
eq('cityjobs.nyc.gov is a known account wall', !!nyc, true);
eq('the wall names its host', nyc?.host, 'cityjobs.nyc.gov');
eq('the wall says an account is required', /account/i.test(nyc?.why || ''), true);
eq('query and hash do not matter', knownAccountWall('https://cityjobs.nyc.gov/job/790198?src=li#top')?.host, 'cityjobs.nyc.gov');
eq('host match is case-insensitive', knownAccountWall('https://CityJobs.NYC.gov/job/1')?.host, 'cityjobs.nyc.gov');

eq('OLAS is NOT on the list — its wall is observed, not assumed',
  knownAccountWall('https://olasjobs.org/apply/123'), null);
eq('a Greenhouse board is not a wall',
  knownAccountWall('https://job-boards.greenhouse.io/anthropic/jobs/5251866008'), null);
eq('SmartRecruiters is not a wall',
  knownAccountWall('https://jobs.smartrecruiters.com/M3USA/744000144813654'), null);
eq('a different nyc.gov host is not matched by suffix',
  knownAccountWall('https://www.nyc.gov/jobs'), null);

for (const bad of [null, undefined, '', 'not a url', '/relative/path', 'javascript:alert(1)', 'file:///etc/passwd']) {
  eq(`rejects ${JSON.stringify(bad)} without throwing`, knownAccountWall(bad), null);
}
eq('every listed host carries a reason VP can read',
  Object.values(KNOWN_ACCOUNT_WALLS).every((v) => typeof v === 'string' && v.length > 20), true);

// ── 2. the finding's shape ────────────────────────────────────────────────
const card = { slug: 'office-of-the-mayor-data-analyst', company: 'OFFICE OF THE MAYOR', role: 'Data Analyst', ats: 'other' };
const url = 'https://cityjobs.nyc.gov/job/782971';

const wall = renderWallFinding(card, url, {
  reason: `the application is behind an account wall — ${nyc.host} ${nyc.why}`,
  note: `**VP must sign in to ${nyc.host} to reach this form.**`,
  inspectedOn: '2026-09-02',
});

eq('the finding carries the dated marker ready-check.py accepts', INSPECTED.test(wall), true);
eq('the date is the one passed in, not re-stamped', wall.includes('**Form inspected: 2026-09-02**'), true);
eq('the finding names the host', wall.includes('cityjobs.nyc.gov requires'), true);
eq('the finding names the company and role', wall.startsWith('# OFFICE OF THE MAYOR — Data Analyst'), true);
eq('the finding carries the apply URL', wall.includes(`**Apply:** ${url}`), true);
eq('the finding carries the generator footer canRewrite() keys on',
  wall.includes('_Generated by generate-answers.mjs'), true);

// parseAnswersMd is what stage-applications reads for packs without
// form-fields.json; a wall finding must read back as a wall.
const parsed = parseAnswersMd(wall);
eq('parseAnswersMd reads the known-wall finding as loginWall', parsed?.loginWall, true);
eq('parseAnswersMd recovers the inspection date', parsed?.inspectedOn, '2026-09-02');
eq('parseAnswersMd sees no fields', parsed?.fields?.length, 0);

// The OLAS wording is unchanged — its parse is already pinned in
// test-cover-letter-requirement.mjs, so this only checks the renderer keeps it.
const olas = renderWallFinding({ slug: 'x', company: 'A District', role: 'Teacher' }, 'https://olasjobs.org/apply/1', {
  reason: 'the application is behind an account wall, so the field list cannot be read without registering',
  note: '**VP must create an account on this board before the form can be filled.**',
  inspectedOn: '2026-08-09',
});
eq('the observed-wall finding still reads back as a wall', parseAnswersMd(olas)?.loginWall, true);
eq('ATS falls back to unknown when the card has none', olas.includes('**ATS:** unknown'), true);

// A completed read that found nothing: dated, host named, NOT a wall.
const empty = renderWallFinding({ slug: 'm3usa-x', company: 'M3USA', role: 'Director of PM', ats: 'other' },
  'https://jobs.smartrecruiters.com/M3USA/744000144813654', {
    reason: 'the form could not be enumerated — the page at jobs.smartrecruiters.com, read via a rendered ' +
      'browser session, exposed no application field, so it must be filled live on the board',
    note: '**Fill this one live on jobs.smartrecruiters.com.**',
    inspectedOn: '2026-09-02',
  });
eq('the not-enumerable finding carries the dated marker', INSPECTED.test(empty), true);
eq('the not-enumerable finding names the host', empty.includes('jobs.smartrecruiters.com'), true);
eq('the not-enumerable finding is NOT a wall', parseAnswersMd(empty)?.loginWall ?? false, false);

// ── 3. no answer content, ever ────────────────────────────────────────────
for (const [name, md] of [['known wall', wall], ['observed wall', olas], ['empty read', empty]]) {
  eq(`${name}: no field table`, /^\|\s*Field\s*\|/m.test(md), false);
  eq(`${name}: no draft`, md.includes('DRAFT — edit before sending'), false);
  eq(`${name}: no blank-by-design row`, md.includes('BLANK BY DESIGN'), false);
  eq(`${name}: no "answered" claim`, /answered \d+/.test(md), false);
  eq(`${name}: does not claim nothing is blocking`, md.includes('Nothing is blocking submission'), false);
}

let pass = 0, fail = 0;
console.log('\nunreadable-form finding — ' + T.length + ' cases\n');
for (const [label, got, want] of T) {
  if (got === want) pass++;
  else { fail++; console.log(`  ❌ ${label}\n     expected ${JSON.stringify(want)}, got ${JSON.stringify(got)}`); }
}
console.log(`${pass}/${T.length} passed`);
if (fail) {
  console.log('\nA finding the gate cannot read fails the nightly forever; a finding with an answer in it is a fabricated form.');
  process.exitCode = 1;
}
