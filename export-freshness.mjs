#!/usr/bin/env node

/**
 * export-freshness.mjs — project the freshness policy into JSON the UI can read.
 *
 * WHY A PROJECTION AND NOT A SHARED IMPORT. The Next app is built from a
 * separate Docker context (`COPY ui/ ./` in Dockerfile.ui), so it cannot import
 * lib/freshness.mjs at build time. The alternative is a second copy of the
 * windows written in TypeScript, which is the two-copies-drift bug this repo
 * keeps re-learning — most recently in rank-leads/recompute-scores, fixed by
 * exporting cvCoverageFacts.
 *
 * ⚠ THE POLICY STAYS IN lib/freshness.mjs. This writes down what it decided.
 * In particular the two parts most likely to drift stay here, in .mjs, and are
 * never re-expressed in the UI:
 *   - whale matching is a case-insensitive SUBSTRING over config/whales.yml
 *   - evergreen is `n >= 4 && pctAlive >= EVERGREEN_PCT` over employer-closure
 * Both are resolved per company below, so the UI does two map lookups and no
 * matching of its own. The one rule it restates is the precedence, which is one
 * line and is asserted in test-freshness-export.mjs:
 *
 *     byTrack[track] ?? byCompany[company] ?? defaultDays
 *
 * That is the same order as maxAgeDaysFor(): a track window wins over whale and
 * evergreen, which is why a civic role at a whale employer gets civic's 60 days
 * rather than the whale's 30.
 *
 * byCompany carries ONLY the companies whose window differs from the default,
 * so it stays small — the rest fall through.
 *
 * Usage: node export-freshness.mjs [--dry-run]
 */

import { readFile, writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import {
  loadFreshnessPolicy, maxAgeDaysFor, TRACK_MAX_AGE_DAYS, FRESH_MAX_AGE_DAYS,
} from './lib/freshness.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, 'data', 'freshness-windows.json');
const DRY = process.argv.includes('--dry-run');

/** Company names on the board. pipeline.md rows are `- [ ] url | company | role`. */
async function companiesInPipeline() {
  const out = new Set();
  try {
    const raw = await readFile(path.join(ROOT, 'data', 'pipeline.md'), 'utf-8');
    for (const line of raw.split('\n')) {
      const parts = line.split('|');
      if (parts.length < 3) continue;
      const company = parts[1].trim();
      if (company) out.add(company);
    }
  } catch { /* no pipeline yet */ }
  return out;
}

async function main() {
  const policy = await loadFreshnessPolicy(ROOT);
  const companies = await companiesInPipeline();

  // Resolved with the REAL function, one company at a time, with no track — so
  // whale and evergreen are the only things that can move the number here.
  const byCompany = {};
  for (const company of companies) {
    const days = maxAgeDaysFor({ company }, policy);
    if (days !== FRESH_MAX_AGE_DAYS) byCompany[company.toLowerCase()] = days;
  }

  const doc = {
    generatedOn: new Date().toISOString().slice(0, 10),
    // ⚠ Read this before changing anything downstream.
    note: 'Generated by export-freshness.mjs from lib/freshness.mjs. Do not hand-edit. '
        + 'Resolution order is byTrack[track] ?? byCompany[company.toLowerCase()] ?? defaultDays.',
    defaultDays: FRESH_MAX_AGE_DAYS,
    byTrack: { ...TRACK_MAX_AGE_DAYS },
    byCompany,
  };

  const json = JSON.stringify(doc, null, 2) + '\n';
  if (DRY) {
    console.log(json);
    console.log(`--dry-run, nothing written (${Object.keys(byCompany).length} companies differ from the ${FRESH_MAX_AGE_DAYS}d default)`);
    return;
  }
  await writeFile(OUT, json);
  console.log(`wrote ${path.relative(ROOT, OUT)}: default ${FRESH_MAX_AGE_DAYS}d, `
    + `${Object.keys(doc.byTrack).length} track window(s), `
    + `${Object.keys(byCompany).length} of ${companies.size} companies differ`);
}

await main();
